/// Which list of sessions a window is showing, as a glyph: a window with a rail down its
/// left for the sidebar, a window with a bar along its bottom for the belt. What the
/// toggle at the head of the window bar wears, so it says where the sessions are now.
///
/// Drawn from their vector outlines as template images, like `AgentGlyph`'s marks, so
/// they take the foreground colour and stay sharp at any size.
public struct SessionListGlyph: View {
    public enum List: CaseIterable, Sendable {
        case sidebar, belt
    }

    public let list: List
    public var size: CGFloat

    public init(_ list: List, size: CGFloat = 22) {
        self.list = list
        self.size = size
    }

    public var body: some View {
        if let image = Self.image(list) {
            Image(nsImage: image)
                .renderingMode(.template)
                .resizable()
                .interpolation(.high)
                .frame(width: size, height: size)
        } else {
            Image(systemName: list == .sidebar ? "sidebar.left" : "dock.rectangle")
                .font(.system(size: size - 5, weight: .semibold))
                .frame(width: size, height: size)
        }
    }

    /// Built once per glyph: `body` runs on every redraw of the window bar.
    @MainActor private static var images: [List: NSImage] = [:]

    @MainActor
    static func image(_ list: List) -> NSImage? {
        if let hit = images[list] { return hit }
        let svg = """
        <svg width="24" height="24" viewBox="0 0 24 24" xmlns="http://www.w3.org/2000/svg">\
        <path fill="black" fill-rule="nonzero" d="\(list.path)"/></svg>
        """
        guard let image = NSImage(data: Data(svg.utf8)) else { return nil }
        image.isTemplate = true
        images[list] = image
        return image
    }
}

